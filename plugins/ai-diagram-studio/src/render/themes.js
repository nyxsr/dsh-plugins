export const THEME_NAMES = Object.keys(BASE)

export function getTheme(name) {
  const theme = BASE[name] ?? BASE.professional
  return { ...theme, kindFill: theme.name === 'monochrome' ? {} : theme.kindFill }
}

export function nodeFill(theme, kind) {
  if (theme.name === 'monochrome') return theme.panel
  return theme.kindFill[kind] ?? theme.panel
}
